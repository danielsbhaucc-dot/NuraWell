#!/usr/bin/env node
// Module inventory + starter-kit coverage + no-owner-name guard.
//  * Every product capability must be a catalog module (apps/web/lib/platform/catalog.ts) — surfaces are already
//    enforced by tests/module-surfaces.test.ts; files outside modules by boundaries.mjs.
//  * The STARTER KIT every new product gets must map to modules; mandatory security/privacy ones must be core.
//  * Coverage = share of apps/* code no longer on the legacy list (the list may only shrink).
//  * No real owner name in new code: tokens are compared by SHA-256 only (no name is stored here).
// Usage: node scripts/modules/inventory.mjs [--write]   (CI runs without --write and fails if INVENTORY.md is stale)
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, findModules } from './lib.mjs';
import { readBaseline } from './boundaries.mjs';

/** Starter kit (Daniel's list). `modules`: catalog ids or packaged module ids that deliver it. `mustBeCore`: cannot be disabled. */
export const STARTER_KIT = [
  { item: 'Auth: 2FA, new-device approval, roles, PII encryption', modules: ['security-core', 'iam', 'field-encryption', 'auth-signup'], mustBeCore: ['security-core', 'iam', 'field-encryption'] },
  { item: 'Privacy/legal: consents, terms, deletion/export, accessibility', modules: ['privacy-retention', 'legal', 'a11y'] },
  { item: 'Billing/licensing: subscription + perpetual, module gating', modules: ['billing', 'licensing'] },
  { item: 'Notifications: email, Telegram, WhatsApp, push (event-driven)', modules: ['notifications'] },
  { item: 'AI: cheap-model router, cost caps, memory', modules: ['ai-engine', 'costs', 'agent'] },
  { item: 'Scheduler/reminders with stale-expiry', modules: ['reminders'] },
  { item: 'Central console auto-registration: CRM, logs, QC, costs', modules: ['module-library-ui', 'logs', 'qc', 'costs'], mustBeCore: ['logs'] },
  { item: 'Hebrew RTL design system, mobile, loading/error, 404', modules: ['ui', 'app-shell'], mustBeCore: ['app-shell'] },
  { item: 'Backups before data changes; CI guards (incl. no-owner-name)', modules: ['audit-log', 'incident-response'], mustBeCore: ['audit-log', 'incident-response'] },
  { item: 'One-command generator proven by the sample product', modules: ['module-library-ui'] },
];
// sha256 of lowercase owner-name tokens (Latin + Hebrew). Plain names are never stored in the repo.
const NAME_HASHES = new Set(['bd3dae5fb91f88a4f0978222dfd58f59a124257cb081486387cbae9df11fb879', 'f3ef4d448ab0f90b3cbf0df52f5af87e7f3e2b66a169d272b8b7ebf0d290cfba', 'cfcc470274a36ae56a2d955fa68b7706435acbb5b3fc14a700d09350f7331bfb']);

export function catalogModules() {
  const src = readFileSync(join(ROOT, 'apps/web/lib/platform/catalog.ts'), 'utf8');
  return [...src.matchAll(/\{ id: '([a-z0-9-]+)', name: '([^']+)', core: (true|false)/g)].map((m) => ({ id: m[1], name: m[2], core: m[3] === 'true' }));
}
export function nameHits(text, hashes = NAME_HASHES) {
  const hits = new Set();
  for (const t of text.toLowerCase().match(/[a-z\u05d0-\u05ea]{4,}/g) ?? []) if (hashes.has(createHash('sha256').update(t).digest('hex'))) hits.add(t.length);
  return hits.size;
}

export function build() {
  const cat = catalogModules(), pk = findModules().map((m) => m.json.id);
  const known = new Set([...cat.map((m) => m.id), ...pk]);
  const errors = [];
  for (const k of STARTER_KIT) {
    for (const id of k.modules) if (!known.has(id)) errors.push(`starter kit "${k.item}": module "${id}" is not registered`);
    for (const id of k.mustBeCore ?? []) if (!cat.find((m) => m.id === id)?.core) errors.push(`starter kit "${k.item}": "${id}" must be core (cannot be disabled)`);
  }
  const files = execFileSync('git', ['ls-files', 'apps'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter((f) => /\.(tsx?|jsx?|mjs)$/.test(f) && !/\/tests?\/|\/e2e\//.test(f));
  const legacy = readBaseline();
  const legacyCode = files.filter((f) => legacy.has(f)).length;
  const legacySet = legacy;
  for (const f of execFileSync('git', ['ls-files', 'packages', 'scripts'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter((f) => /\.(tsx?|jsx?|mjs|json|md|txt)$/.test(f))) {
    if (legacySet.has(f) || !existsSync(join(ROOT, f))) continue;
    if (nameHits(readFileSync(join(ROOT, f), 'utf8'))) errors.push(`${f}: contains the owner's real name; use a role (platform.founder) instead`);
  }
  const pct = files.length ? Math.round((1000 * (files.length - legacyCode)) / files.length) / 10 : 100;
  const md = [
    '<!-- GENERATED by `node scripts/modules/inventory.mjs --write`. CI fails if stale. -->',
    '# Module inventory', '',
    `Catalog modules: ${cat.length} (core: ${cat.filter((m) => m.core).length}). Packaged modules (module.json): ${pk.length}.`,
    `App code already modular: ${pct}% (${files.length - legacyCode}/${files.length} files; the rest is on modules/legacy-app-files.txt and may only shrink).`, '',
    '| id | name | core (cannot disable) | packaged |', '|---|---|---|---|',
    ...cat.map((m) => `| \`${m.id}\` | ${m.name} | ${m.core ? 'yes' : 'no'} | ${pk.includes(m.id) ? 'yes' : 'not yet'} |`), '',
    '## Starter kit for every new product', '', '| item | modules |', '|---|---|',
    ...STARTER_KIT.map((k) => `| ${k.item} | ${k.modules.map((x) => '`' + x + '`').join(', ')} |`), '',
  ].join('\n');
  return { md, errors };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { md, errors } = build();
  const out = join(ROOT, 'modules/INVENTORY.md');
  if (process.argv.includes('--write')) writeFileSync(out, md);
  else if (!existsSync(out) || readFileSync(out, 'utf8') !== md) errors.push('modules/INVENTORY.md is stale: run node scripts/modules/inventory.mjs --write');
  if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
  console.log('inventory ok');
}
