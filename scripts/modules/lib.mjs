// Shared helpers for the module CLI. Zero dependencies (Node built-ins only) so any repo can vendor it.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PKG_DIRS = ['packages', 'packages/@platform'];

export function findModules(root = ROOT) {
  const out = [];
  for (const d of PKG_DIRS) {
    const abs = join(root, d);
    if (!existsSync(abs)) continue;
    for (const name of readdirSync(abs)) {
      const f = join(abs, name, 'module.json');
      if (existsSync(f)) out.push({ dir: join(d, name), file: f, json: JSON.parse(readFileSync(f, 'utf8')) });
    }
  }
  return out.sort((a, b) => a.json.id.localeCompare(b.json.id));
}

const REQUIRED = ['id', 'package', 'version', 'distribution', 'category', 'toggleable', 'description', 'requires', 'env', 'migrations', 'conformance'];
const SECRETISH = /(sk_|pk_live|eyJ|-----BEGIN|:\/\/[^/]*:[^@]*@)/;

/** Validates one module. Returns a list of human-readable errors (empty = ok). */
export function validateModule(m, all, root = ROOT) {
  const e = [];
  const j = m.json;
  for (const k of REQUIRED) if (!(k in j)) e.push(`missing "${k}"`);
  if (j.id && !/^[a-z][a-z0-9-]*$/.test(j.id)) e.push('bad id');
  if (j.version && !/^\d+\.\d+\.\d+$/.test(j.version)) e.push('version must be semver x.y.z');
  if (!['internal', 'shareable', 'sellable'].includes(j.distribution)) e.push('distribution must be internal|shareable|sellable');
  if (['security', 'privacy'].includes(j.category) && j.toggleable !== false) e.push('security/privacy modules must be toggleable:false (always on)');
  for (const n of j.env ?? []) if (!/^[A-Z][A-Z0-9_]*$/.test(n)) e.push(`env entry "${n}" must be a NAME only`);
  if (SECRETISH.test(readFileSync(m.file, 'utf8'))) e.push('module.json looks like it contains a secret');
  for (const f of ['README.he.md', 'CHANGELOG.md', 'llms.txt', 'package.json']) if (!existsSync(join(root, m.dir, f))) e.push(`missing ${f}`);
  const pj = existsSync(join(root, m.dir, 'package.json')) ? JSON.parse(readFileSync(join(root, m.dir, 'package.json'), 'utf8')) : {};
  if (pj.name && pj.name !== j.package) e.push(`package.json name ${pj.name} != ${j.package}`);
  if (pj.version && pj.version !== j.version) e.push(`package.json version ${pj.version} != ${j.version}`);
  const cl = existsSync(join(root, m.dir, 'CHANGELOG.md')) ? readFileSync(join(root, m.dir, 'CHANGELOG.md'), 'utf8') : '';
  if (j.version && !cl.includes(`## ${j.version}`)) e.push(`CHANGELOG.md has no "## ${j.version}" entry`);
  for (const t of j.tests ?? []) if (!existsSync(join(root, t))) e.push(`test file not found: ${t}`);
  for (const mig of j.migrations ?? []) if (!existsSync(join(root, m.dir, mig)) && !existsSync(join(root, 'supabase/migrations', mig))) e.push(`migration not found: ${mig}`);
  for (const dep of Object.keys(j.requires?.modules ?? {})) if (!all.some((x) => x.json.id === dep)) e.push(`requires unknown module "${dep}"`);
  if (j.distribution !== 'internal') {
    // shareable/sellable: zero coupling to the product app.
    const src = join(root, m.dir, 'src');
    for (const f of walk(src)) {
      const s = readFileSync(f, 'utf8');
      if (/from ['"]@\/|from ['"](\.\.\/)+apps\//.test(s)) e.push(`${f.slice(root.length + 1)} imports app code`);
      if (/process\.env/.test(s)) e.push(`${f.slice(root.length + 1)} reads process.env (inject config instead)`);
    }
  }
  return e;
}

/** Topological order; throws on cycles. */
export function dependencyOrder(mods) {
  const byId = new Map(mods.map((m) => [m.json.id, m]));
  const seen = new Map();
  const out = [];
  const visit = (id, path) => {
    if (seen.get(id) === 'done') return;
    if (seen.get(id) === 'visiting') throw new Error(`dependency cycle: ${[...path, id].join(' -> ')}`);
    seen.set(id, 'visiting');
    for (const d of Object.keys(byId.get(id)?.json.requires?.modules ?? {})) if (byId.has(d)) visit(d, [...path, id]);
    seen.set(id, 'done');
    out.push(byId.get(id));
  };
  for (const id of byId.keys()) visit(id, []);
  return out;
}

export function* walk(dir) {
  if (!existsSync(dir)) return;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (/\.(ts|tsx|mjs|js)$/.test(e.name)) yield p;
  }
}

export function renderIndex(mods) {
  const rows = mods.map((m) => `| \`${m.json.id}\` | \`${m.json.package}\` | ${m.json.version} | ${m.json.distribution} | ${m.json.category} | ${m.json.toggleable ? 'yes' : 'always on'} | [README](../${m.dir}/README.he.md) · [llms.txt](../${m.dir}/llms.txt) | ${m.json.description} |`);
  return [
    '<!-- GENERATED by `node scripts/modules/index.mjs` from every module.json. Do not edit by hand; CI fails if stale. -->',
    '# Module index',
    '',
    'Read `/AGENTS.md` first. Plan and catalog: `docs/architecture/MODULE_CATALOG.he.md`.',
    '',
    '| id | package | version | distribution | category | toggle | docs | description |',
    '|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

