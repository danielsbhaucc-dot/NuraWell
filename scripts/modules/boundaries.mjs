#!/usr/bin/env node
// Module-first CI rule: feature code lives in packages/@platform/<module>; app shells only compose modules.
// A file under apps/* fails the check unless it is (a) legacy, listed in modules/legacy-app-files.txt
// ("to be modularized"; this list may only shrink), or (b) thin routing/layout glue on the allow-list.
// Usage: node scripts/modules/boundaries.mjs [--update-baseline]   (update only to REMOVE entries / initial seed)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';
import { findAreas, ownerOf } from './areas.mjs';

export const GLUE_MAX_LINES = 80;
// Routing/layout glue + non-code assets. Everything else under apps/* is feature code.
export const ALLOW = [
  /^apps\/[^/]+\/app\/(.+\/)?(page|layout|template|loading|error|global-error|not-found|default|route|opengraph-image|icon|sitemap|robots|manifest)\.(tsx?|jsx?)$/,
  /^apps\/[^/]+\/(proxy|middleware|instrumentation|next-env\.d)\.ts$/,
  /^apps\/[^/]+\/[^/]+\.(json|js|mjs|cjs|toml|md)$/, // app-level config + docs
  /^apps\/[^/]+\/tests\//,
  /^apps\/[^/]+\/e2e\//,
  /^apps\/[^/]+\/public\//,
  /\.(css|svg|png|jpe?g|webp|ico|woff2?|txt|md)$/,
];
const GLUE_SIZE_CHECKED = /\/app\/.*\.(tsx?|jsx?)$|\/(proxy|middleware)\.ts$/;

export function classify(files, legacy, read = (f) => readFileSync(join(ROOT, f), 'utf8'), areas = findAreas()) {
  const errors = [];
  for (const f of files) {
    if (!f.startsWith('apps/')) continue;
    const owner = ownerOf(f, areas);
    if (legacy.has(f)) {
      if (owner) errors.push(`${f}: owned by module "${owner}" but still on modules/legacy-app-files.txt — remove the line (the list only shrinks).`);
      continue;
    }
    if (owner) continue; // feature code inside an area module (modules/<id>/module.json "owns")
    if (!ALLOW.some((r) => r.test(f))) { errors.push(`${f}: feature code outside modules. Create it with \`npx @platform/modules new <id>\` and import it from the app.`); continue; }
    if (GLUE_SIZE_CHECKED.test(f)) {
      const n = read(f).split('\n').length;
      if (n > GLUE_MAX_LINES) errors.push(`${f}: glue file has ${n} lines (> ${GLUE_MAX_LINES}); move the logic into a module.`);
    }
  }
  return errors;
}

const BASELINE = join(ROOT, 'modules/legacy-app-files.txt');
export function readBaseline(file = BASELINE) {
  return new Set(existsSync(file) ? readFileSync(file, 'utf8').split('\n').filter((l) => l && !l.startsWith('#')) : []);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', 'apps'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean).filter((f) => existsSync(join(ROOT, f)));
  if (process.argv.includes('--update-baseline')) {
    const old = readBaseline();
    const keep = files.filter((f) => classify([f], new Set()).length > 0 && (old.size === 0 || old.has(f)));
    writeFileSync(BASELINE, '# Legacy app feature files, to be modularized. This list may only SHRINK.\n# Generated by: node scripts/modules/boundaries.mjs --update-baseline\n' + keep.sort().join('\n') + '\n');
    console.log(`baseline: ${keep.length} legacy files`);
    process.exit(0);
  }
  const errors = classify(files, readBaseline());
  // The legacy list may only SHRINK: compare with the base branch when it is available (CI fetches it).
  const base = process.env.MODULES_BASE_REF || 'origin/main';
  try {
    const old = new Set(execFileSync('git', ['show', `${base}:modules/legacy-app-files.txt`], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split('\n').filter((l) => l && !l.startsWith('#')));
    for (const l of readBaseline()) if (!old.has(l)) errors.push(`${l}: added to modules/legacy-app-files.txt — new feature code must live in a module, the list may only shrink.`);
  } catch { console.warn(`(skipping shrink-only check: ${base} not available)`); }
  if (errors.length) { console.error('✖ module-first boundary violations:\n  ' + errors.join('\n  ')); process.exit(1); }
  console.log('module boundaries: OK');
}
