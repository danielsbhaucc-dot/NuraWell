// Inlines docs/security/restore/*.html into apps/web/lib/security/backup-docs.generated.ts (run after editing them).
import { readFileSync, writeFileSync } from 'node:fs';
const d = new URL('../../docs/security/restore/', import.meta.url);
const css = readFileSync(new URL('_style.css', d), 'utf8');
const load = (f) => readFileSync(new URL(f, d), 'utf8').replace('/*STYLE*/', css);
const out = `// GENERATED by scripts/keys/build-backup-docs.mjs. Do not edit by hand.
export const RESTORE_HTML = ${JSON.stringify(load('offline-restore.html'))};
export const GUIDE_HTML = ${JSON.stringify(load('guide.html'))};
export const SHARE_CARD_HTML = ${JSON.stringify(load('share-card.html'))};
export const DR_HTML = ${JSON.stringify(load('disaster-recovery.html'))};
`;
writeFileSync(new URL('../../apps/web/lib/security/backup-docs.generated.ts', import.meta.url), out);
console.log('ok', out.length);
