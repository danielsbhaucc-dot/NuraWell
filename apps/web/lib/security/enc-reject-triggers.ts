/**
 * Source of the generated enc-reject trigger migration (scripts/gen-enc-triggers.mts; CI: tests/enc-reject-triggers.test.ts).
 * Every FIELD_V2 table gets `zz_enc_reject_plaintext`, a BEFORE INSERT OR UPDATE trigger listing its registered,
 * non-BLOCKED sensitive columns. Once `field_enc_enforcement.active` is true for the table, any write that sets one of
 * those columns to a non-null value without the enc:v1:/enc:v2: prefix raises (UPDATE: changed columns only).
 * Named zz_ so it fires after every other BEFORE trigger and sees the final row.
 */
import { ENCRYPTED_TABLES, FIELD_V2_TABLES, isBlocked } from './field-registry';

export const ENC_TRIGGER_MARK = '-- enc-reject-triggers: generated by apps/web/scripts/gen-enc-triggers.mts — do not edit';

export function encRejectSpec(): Array<[string, string[]]> {
  const reg = ENCRYPTED_TABLES as Record<string, { columns: Record<string, string> }>;
  return [...FIELD_V2_TABLES].sort().map((t) => [t, Object.keys(reg[t]?.columns ?? {}).filter((c) => !isBlocked(t, c)).sort()] as [string, string[]])
    .filter(([, cs]) => cs.length > 0);
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function encRejectTriggersSql(): string {
  const spec = encRejectSpec();
  const out = [ENC_TRIGGER_MARK, `-- spec ${JSON.stringify(Object.fromEntries(spec))}`, ''];
  out.push('insert into public.field_enc_enforcement (table_name) values');
  out.push(spec.map(([t]) => `  (${lit(t)})`).join(',\n') + '\non conflict (table_name) do nothing;', '');
  for (const [t, cs] of spec) {
    out.push(
      `do $g$ begin if to_regclass('public.${t}') is not null then`,
      `  drop trigger if exists zz_enc_reject_plaintext on public.${t};`,
      `  create trigger zz_enc_reject_plaintext before insert or update on public.${t}`,
      `    for each row execute function public.enc_reject_plaintext(${cs.map(lit).join(', ')});`,
      `end if; end $g$;`,
    );
  }
  return out.join('\n') + '\n';
}
