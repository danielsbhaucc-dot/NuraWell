// Regenerates lib/legal/security-docs.generated.ts from /docs/security/*.he.md (shown in Ops → משפטי → אבטחה ופרטיות).
// A CI test fails when the two drift: run `node scripts/gen-security-docs.mjs` after editing the docs.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../../docs/security');
const files = readdirSync(src).filter((f) => f.endsWith('.he.md')).sort((a, b) => (a === 'README.he.md' ? -1 : b === 'README.he.md' ? 1 : a.localeCompare(b)));
const docs = files.map((f) => {
  const md = readFileSync(join(src, f), 'utf8');
  const title = (md.match(/^#\s+(.+)$/m)?.[1] ?? f).trim();
  return { slug: f.replace(/\.he\.md$/, '').toLowerCase(), file: f, title, markdown: md };
});
writeFileSync(join(here, '../lib/legal/security-docs.generated.ts'),
  `// GENERATED by scripts/gen-security-docs.mjs from docs/security — do not edit by hand.\nexport type SecurityDoc = { slug: string; file: string; title: string; markdown: string };\nexport const SECURITY_DOCS: SecurityDoc[] = ${JSON.stringify(docs, null, 2)};\n`);
console.log(`wrote ${docs.length} docs`);
